"""The SDK's public API as data: every name ``trellis.memory`` exports, each with what a caller
depends on — a function's or method's signature, a class's public methods and properties, a
pydantic model's fields (name, annotation, whether it is required, its default), an enum's
members, a constant's value. ``sdk/python/tests/test_public_api.py`` compares it with the
committed snapshot (``sdk/python/public_api.json``); ``--check-base`` compares the snapshot with
the base branch's in CI, so a changed signature needs a new SDK version and a CHANGELOG entry
naming it.

Regenerate the snapshot after an intended change (it refuses unless the version in
``sdk/python/pyproject.toml`` moved past the snapshot's and the CHANGELOG names it)::

    python scripts/sdk_api.py --update

CI holds the same against the base branch (a snapshot regenerated by hand, under the same
version, is caught there)::

    python scripts/sdk_api.py --check-base origin/main
"""

from __future__ import annotations

import contextlib
import enum
import inspect
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path
from typing import Any, Final, ForwardRef

ROOT: Final = Path(__file__).resolve().parents[1]
SDK: Final = ROOT / "sdk" / "python"
SNAPSHOT: Final = SDK / "public_api.json"
PYPROJECT: Final = SDK / "pyproject.toml"
CHANGELOG: Final = ROOT / "CHANGELOG.md"
#: An object's address in its repr (a sentinel default): not part of the API, and never stable.
ADDRESS: Final = re.compile(r" at 0x[0-9a-fA-F]+")
#: A dotted name (``typing.Literal``, ``trellis.memory.models.SkillView``): kept as its last part.
QUALIFIED: Final = re.compile(r"\b(?:[A-Za-z_]\w*\.)+([A-Za-z_]\w*)")


def version() -> str:
    """The SDK's version, as ``sdk/python/pyproject.toml`` has it."""
    return str(tomllib.loads(PYPROJECT.read_text())["project"]["version"])


def named_in_changelog(text: str, sdk_version: str) -> bool:
    """Whether the CHANGELOG names this SDK version (``trellis-memory`` 0.5.0, SDK 0.5.0)."""
    escaped = re.escape(sdk_version)
    return re.search(rf"(trellis-memory`?|SDK)\s+`?{escaped}\b", text) is not None


def _signature(target: Any) -> str:
    try:
        return ADDRESS.sub("", str(inspect.signature(target)))
    except (TypeError, ValueError):  # a builtin without one
        return "(...)"


def _members(cls: type) -> dict[str, str]:
    """A class's public methods (their signatures) and properties, its own and inherited from
    the SDK's own bases (not ``object``'s or pydantic's)."""
    found: dict[str, str] = {}
    for name, value in inspect.getmembers(cls):
        if name.startswith("_") and name not in ("__init__", "__call__"):
            continue
        defined = next((c for c in cls.__mro__ if name in c.__dict__), None)
        if defined is None or not defined.__module__.startswith("trellis."):
            continue
        raw = defined.__dict__[name]
        if isinstance(raw, property):
            found[name] = "property"
        elif isinstance(raw, (staticmethod, classmethod)) or inspect.isfunction(value):
            kind = type(raw).__name__ if isinstance(raw, (staticmethod, classmethod)) else ""
            found[name] = f"{kind} {_signature(value)}".strip()
    return dict(sorted(found.items()))


def _annotation(annotation: Any) -> str:
    """A field's annotation as text that does not depend on when it is read: a forward
    reference by what it names, every qualified name by its last part."""
    if isinstance(annotation, ForwardRef):
        text = annotation.__forward_arg__
    elif isinstance(annotation, type):
        text = annotation.__name__
    else:
        text = repr(annotation)
    return QUALIFIED.sub(r"\1", text)


def _fields(model: Any) -> dict[str, str]:
    """A pydantic model's fields: annotation, required or its default."""
    found: dict[str, str] = {}
    with contextlib.suppress(Exception):  # forward references resolved, where they can be
        model.model_rebuild()
    for name, field in model.model_fields.items():
        shown = _annotation(field.annotation)
        if field.is_required():
            found[name] = f"{shown} (required)"
        else:
            default = field.default_factory if field.default_factory else field.default
            found[name] = f"{shown} = {default!r}" if not callable(default) else f"{shown} = ..."
    return found


def describe(target: Any) -> dict[str, Any]:
    """What a caller of one exported name depends on."""
    if inspect.isclass(target):
        if issubclass(target, enum.Enum):
            return {"kind": "enum", "members": {m.name: repr(m.value) for m in target}}
        described: dict[str, Any] = {
            "kind": "class",
            "bases": [b.__name__ for b in target.__bases__],
            "members": _members(target),
        }
        if hasattr(target, "model_fields"):
            described["kind"] = "model"
            described["fields"] = _fields(target)
        return described
    if callable(target):
        return {"kind": "function", "signature": _signature(target)}
    return {"kind": "value", "value": ADDRESS.sub("", repr(target))}


def snapshot() -> dict[str, Any]:
    """The public API of ``trellis.memory`` now: each name in its ``__all__``."""
    import trellis.memory as sdk

    return {name: describe(getattr(sdk, name)) for name in sorted(sdk.__all__)}


def stored() -> dict[str, Any]:
    return json.loads(SNAPSHOT.read_text())


def changes(before: dict[str, Any], after: dict[str, Any]) -> list[str]:
    """What differs between two API descriptions, one line per name."""
    lines = []
    for name in sorted(set(before) | set(after)):
        if name not in after:
            lines.append(f"removed: {name}")
        elif name not in before:
            lines.append(f"added: {name}")
        elif before[name] != after[name]:
            lines.append(f"changed: {name}")
    return lines


def update() -> str:
    """Write the snapshot of the API now, under the SDK's version — refused when the API
    changed but the version did not move past the snapshot's, or the CHANGELOG does not name
    the new version."""
    api, now = snapshot(), version()
    if SNAPSHOT.exists():
        old = stored()
        if old["api"] == api:
            return f"unchanged: the public API of trellis-memory {old['version']}"
        if old["version"] == now:
            raise SystemExit(
                f"the public API changed ({'; '.join(changes(old['api'], api))}) but the SDK "
                f"version is still {now}: bump sdk/python/pyproject.toml first"
            )
    if not named_in_changelog(CHANGELOG.read_text(), now):
        raise SystemExit(
            f"CHANGELOG.md names no trellis-memory {now}: add the entry saying what changed"
        )
    SNAPSHOT.write_text(json.dumps({"version": now, "api": api}, indent=1, sort_keys=True) + "\n")
    return f"written: the public API of trellis-memory {now}"


def _at(ref: str, path: Path) -> str | None:
    """``path`` as it is at the git ``ref`` (``None``: not there)."""
    relative = path.relative_to(ROOT).as_posix()
    found = subprocess.run(  # noqa: S603 - git, on this checkout, with a ref CI names
        ["git", "show", f"{ref}:{relative}"],  # noqa: S607
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    return found.stdout if found.returncode == 0 else None


def check_base(ref: str) -> str:
    """The committed snapshot against the one at ``ref`` (the base branch): a changed public
    API needs a version past the base's, which the CHANGELOG names. Raises ``SystemExit``
    saying what is missing."""
    base = _at(ref, SNAPSHOT)
    if base is None:
        return f"no snapshot at {ref}: nothing to compare"
    before, after = json.loads(base), stored()
    differs = changes(before["api"], after["api"])
    if not differs:
        return f"the public API is {ref}'s"
    base_project = _at(ref, PYPROJECT)
    base_version = tomllib.loads(base_project)["project"]["version"] if base_project else None
    if version() == base_version:
        raise SystemExit(
            f"the public API changed against {ref} ({'; '.join(differs)}) but the SDK version is "
            f"still {base_version}: bump sdk/python/pyproject.toml"
        )
    if not named_in_changelog(CHANGELOG.read_text(), version()):
        raise SystemExit(f"CHANGELOG.md names no trellis-memory {version()}")
    return f"the public API changed against {ref} under trellis-memory {version()}: allowed"


if __name__ == "__main__":
    match sys.argv[1:]:
        case ["--update"]:
            print(update())  # noqa: T201 - a command line tool
        case ["--check-base", ref]:
            print(check_base(ref))  # noqa: T201
        case _:
            raise SystemExit("usage: python scripts/sdk_api.py --update | --check-base <ref>")
