"""The vendored bifrost-sdk and trellis-contracts must match their sources.

``vendor/bifrost-sdk`` and ``vendor/trellis-contracts`` are generated by ``make vendor`` and
git-ignored, and the installed packages resolve to them — so a fix made in the real bifrost-sdk repository does not reach
this service until someone regenerates it. Every Makefile test target already depends on
``vendor``; running ``pytest`` directly, which is what most people do, does not.

That silence is the problem. It happened: the 429 handling was fixed upstream, the vendored
copy still carried ``response.text[:500]``, and the whole suite passed against the stale
code — including the tests that exist to cover rate limiting. The failure mode of a stale
vendor is a green run, which is why this is a test and not a comment.

Skipped, not failed, when the source is not on disk: a CI job that checks out only this
repository has nothing to compare against, and the image build regenerates the copy anyway.
"""

from __future__ import annotations

import filecmp
import os
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
#: Each vendored package: its directory under vendor/, the variable naming its checkout (as
#: ``make vendor`` reads it), the default checkout beside this repository, its import path.
PACKAGES = {
    "bifrost-sdk": ("BIFROST_SDK", "bifrost-sdk", ("bifrost_sdk",)),
    "trellis-contracts": ("TRELLIS_CONTRACTS", "agent-contracts", ("trellis", "contracts")),
}


def _paths(name: str) -> tuple[Path, Path]:
    variable, checkout, package = PACKAGES[name]
    vendored = REPO / "vendor" / name / "src" / Path(*package)
    source = Path(os.environ.get(variable, REPO.parent / checkout)) / "src" / Path(*package)
    return vendored, source


def _python_files(root: Path) -> dict[str, Path]:
    return {
        str(path.relative_to(root)): path
        for path in sorted(root.rglob("*.py"))
        if "__pycache__" not in path.parts
    }


def _source_or_skip(source: Path) -> None:
    if not source.is_dir():
        pytest.skip(f"source not at {source}")


@pytest.mark.parametrize("name", sorted(PACKAGES))
def test_the_vendored_copy_matches_its_source(name: str) -> None:
    vendored_root, source_root = _paths(name)
    _source_or_skip(source_root)
    assert vendored_root.is_dir(), (
        f"{vendored_root} is missing — run `make vendor`. The installed {name} resolves here."
    )

    source = _python_files(source_root)
    vendored = _python_files(vendored_root)

    assert set(vendored) == set(source), (
        "the vendored copy has a different set of modules than the source "
        f"(only in vendor: {sorted(set(vendored) - set(source))}; "
        f"only in source: {sorted(set(source) - set(vendored))}) — run `make vendor`"
    )

    stale = [
        file
        for file, path in source.items()
        if not filecmp.cmp(path, vendored[file], shallow=False)
    ]
    assert not stale, (
        f"the vendored {name} is stale: {sorted(stale)} differ from {source_root}. "
        f"Run `make vendor`. Until you do, the suite tests code that is not what ships."
    )


@pytest.mark.parametrize("name", sorted(PACKAGES))
def test_the_installed_package_is_the_vendored_one(name: str) -> None:
    """If this ever stops being true, the test above is guarding the wrong directory."""
    import importlib

    vendored, source = _paths(name)
    _source_or_skip(source)
    module = importlib.import_module(".".join(PACKAGES[name][2]))
    installed = Path(module.__file__ or "").resolve().parent
    assert installed == vendored.resolve(), (
        f"{name} imports from {installed}, not the vendored copy at {vendored}"
    )
